"""Generates syscalls_amd64.go (syscall name -> number on x86-64) from the kernel headers.

    python3 gen_syscalls.py /usr/include/x86_64-linux-gnu/asm/unistd_64.h > syscalls_amd64.go
"""
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "/usr/include/x86_64-linux-gnu/asm/unistd_64.h"
pairs = []
for line in open(src):
    m = re.match(r"#define __NR_(\w+)\s+(\d+)", line)
    if m:
        pairs.append((m.group(1), int(m.group(2))))
print("// Code generated by gen_syscalls.py from asm/unistd_64.h; DO NOT EDIT.")
print()
print("package seccomp")
print()
print("// syscallsAMD64 maps x86-64 system call names to their numbers.")
print("var syscallsAMD64 = map[string]uint32{")
for name, nr in sorted(pairs, key=lambda p: p[1]):
    print(f'\t"{name}": {nr},')
print("}")
